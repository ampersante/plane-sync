class InsertRemoveTests(unittest.TestCase):
    """New items are inserted in renderer order; vanished items are removed
    (deletion oracle: absent from the existing-items directory)."""

    def test_new_inserted_and_disappeared_removed(self):
        carried_line = "| PRJ-1 | carried | Todo | medium |  |  |  |"
        deleted_line = "| PRJ-2 | deleted | Todo | low |  |  |  |"
        fresh_item = {"id": "u3", "sequence_id": 3, "name": "new item",
                      "priority": "high", "state": "s1", "assignees": [],
                      "labels": [], "parent": "", "module_ids": [],
                      "description_html": ""}
        maps = {"state": {"s1": {"name": "Todo", "group": "unstarted"}},
                "label": {}, "member": {}, "item_module": {}}
        data = {
            "work_items": [fresh_item],
            "since": {
                # u2 is gone: deleted between the snapshots
                "directory": {"u1": {"seq": 1, "module_ids": []},
                              "u3": {"seq": 3, "module_ids": []}},
                "top_rows": {1: carried_line, 2: deleted_line},
                "children": {},
                "desc_blocks": {},
            },
        }
        rows = build_item_rows(data, maps, "PRJ")
        self.assertEqual([seq for seq, _ in rows["top"]], [1, 3])
        self.assertEqual(rows["top"][0][1], carried_line)  # byte-in-byte
        self.assertEqual(rows["top"][1][1],
                         "| PRJ-3 | new item | Todo | high |  |  |  |")

    def test_fresh_child_joins_carried_parent_block(self):
        heading = "#### PRJ-1: carried"
        carried_child = "| PRJ-2 | carried child | Todo | low |  |  |"
        fresh_child = {"id": "u3", "sequence_id": 3, "name": "new child",
                       "priority": "high", "state": "s1", "assignees": [],
                       "labels": [], "parent": "u1", "module_ids": [],
                       "description_html": ""}
        maps = {"state": {"s1": {"name": "Todo", "group": "unstarted"}},
                "label": {}, "member": {}, "item_module": {}}
        data = {
            "work_items": [fresh_child],
            "since": {
                "directory": {"u1": {"seq": 1, "module_ids": []},
                              "u2": {"seq": 2, "module_ids": []},
                              "u3": {"seq": 3, "module_ids": []}},
                "top_rows": {1: "| PRJ-1 | carried | Todo | medium |  |  |  |"},
                "children": {1: {"heading": heading, "rows": {2: carried_child}}},
                "desc_blocks": {},
            },
        }
        rows = build_item_rows(data, maps, "PRJ")
        self.assertEqual([seq for seq, _ in rows["top"]], [1])
        self.assertEqual(len(rows["children"]), 1)
        pseq, out_heading, out_rows = rows["children"][0]
        self.assertEqual((pseq, out_heading), (1, heading))  # heading carried
        self.assertEqual([seq for seq, _ in out_rows], [2, 3])
        self.assertEqual(out_rows[0][1], carried_child)
        self.assertEqual(out_rows[1][1],
                         "| PRJ-3 | new child | Todo | high |  |  |")


class ModuleCountsTests(unittest.TestCase):
    """DEC-016 counters from the v2 directory walk's module_ids (verified
    equal to v1 module-issues membership): changed items resolve their state
    group via state_id, carried items via the previous row's State cell."""

    def test_merged_membership_counts(self):
        fresh_item = {"id": "u3", "sequence_id": 3, "name": "new", "priority": "high",
                      "state": "s2", "assignees": [], "labels": [], "parent": "",
                      "module_ids": ["m1"], "description_html": ""}
        carried_top = "| PRJ-1 | carried | In Progress | medium |  |  | M1 |"
        carried_child = "| PRJ-2 | carried child | Todo | low |  |  |"
        data = {
            "modules": [{"id": "m1", "name": "M1", "sort_order": 0,
                         "total_issues": 3}],
            "states": [{"id": "s1", "name": "In Progress", "group": "started"},
                       {"id": "s2", "name": "Todo", "group": "unstarted"}],
            "work_items": [fresh_item],
            "since": {
                "directory": {
                    "u1": {"seq": 1, "module_ids": ["m1"]},
                    "u2": {"seq": 2, "module_ids": ["m1"]},
                    "u3": {"seq": 3, "module_ids": ["m1"]},
                },
                "top_rows": {1: carried_top},
                "children": {1: {"heading": "#### PRJ-1: carried",
                                 "rows": {2: carried_child}}},
            },
        }
        maps = {"state": {"s2": {"name": "Todo", "group": "unstarted"}}}
        counts = build_module_counts(data, maps)
        # u1 carried (state name via states list), u2 carried child (children
        # row), u3 fresh (state_id) — all three counted in m1
        self.assertEqual(counts["m1"]["started"], 1)
        self.assertEqual(counts["m1"]["unstarted"], 2)

    def test_deleted_items_drop_out_of_counts(self):
        carried_line = "| PRJ-1 | carried | Todo | medium |  |  | M1 |"
        data = {
            "modules": [{"id": "m1", "name": "M1", "sort_order": 0,
                         "total_issues": 0}],
            "states": [{"id": "s1", "name": "Todo", "group": "unstarted"}],
            "work_items": [],
            "since": {
                # u1 alive, u2 deleted (absent from the directory)
                "directory": {"u1": {"seq": 1, "module_ids": ["m1"]}},
                "top_rows": {1: carried_line, 2: "| PRJ-2 | gone | Todo | low |  |  | M1 |"},
                "children": {},
            },
        }
        counts = build_module_counts(data, {})
        self.assertEqual(counts["m1"]["unstarted"], 1)


