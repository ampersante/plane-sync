class SincePrerequisiteTests(unittest.TestCase):
    """--since CLI prerequisites: without auto mode it exits before any v2
    request; a previous file without a Listed: line asks for a full re-snapshot."""

    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        self._old_argv = sys.argv
        self._old_get_api_version = plane_snapshot.get_api_version
        self._old_v2_enabled = plane_snapshot.v2_enabled

    def tearDown(self):
        sys.argv = self._old_argv
        plane_snapshot.get_api_version = self._old_get_api_version
        plane_snapshot.v2_enabled = self._old_v2_enabled
        self._tmp.cleanup()

    def _write_prev(self, with_listed: bool) -> Path:
        lines = _PREV_SNAPSHOT.splitlines()
        if not with_listed:
            lines = [l for l in lines if not l.startswith("Listed:")]
        path = Path(self._tmp.name) / f"prev_{with_listed}.md"
        path.write_text("\n".join(lines) + "\n", encoding="utf-8")
        return path

    def _run_main(self, prev: Path) -> tuple:
        sys.argv = ["plane_snapshot.py", "--since", str(prev), "-w", "w", "-p", "p"]
        err = io.StringIO()
        try:
            with redirect_stderr(err):
                plane_snapshot.main()
        except SystemExit as e:
            return e.code, err.getvalue()
        return None, err.getvalue()

    def test_since_without_auto_mode_errors_before_network(self):
        prev = self._write_prev(with_listed=True)
        plane_snapshot.get_api_version = lambda: "1"

        def boom():
            raise AssertionError("v2 probe must not run when mode is not auto")

        plane_snapshot.v2_enabled = boom
        code, err = self._run_main(prev)
        self.assertEqual(code, 1)
        self.assertIn("api_version", err)
        self.assertIn("auto", err)

    def test_since_missing_prev_file_errors(self):
        code, err = self._run_main(Path(self._tmp.name) / "nope.md")
        self.assertEqual(code, 1)
        self.assertIn("not found", err)

    def test_since_without_listed_line_errors(self):
        prev = self._write_prev(with_listed=False)
        plane_snapshot.get_api_version = lambda: "auto"
        plane_snapshot.v2_enabled = lambda: True  # unreachable in this order
        code, err = self._run_main(prev)
        self.assertEqual(code, 1)
        self.assertIn("Listed:", err)
        self.assertIn("full snapshot", err)


class ListedHeaderTests(unittest.TestCase):
    """The `Listed:` line is part of the sanctioned header delta (REQ-07) and
    is written in every mode, right under `Generated:`."""

    def test_render_includes_listed_line(self):
        data = {
            "states": [{"id": "s1", "name": "Todo", "group": "unstarted",
                        "sequence": 0}],
            "labels": [], "members": [], "modules": [],
            "work_items": [], "module_membership": {}, "relations": {},
            "include_descriptions": False, "pages": [], "intake": [],
            "listed_at": "2026-01-01T00:00:00Z", "item_count": 0,
        }
        data["module_counts"] = build_module_counts(data, {})
        data["item_rows"] = build_item_rows(data, {}, "PRJ")
        data["desc_blocks"] = build_desc_blocks(data, {}, "PRJ")
        md = render_markdown(data, {}, [], "w", "12345678-abcd", "PRJ")
        lines = md.splitlines()
        self.assertTrue(lines[1].startswith("Generated:"))
        self.assertEqual(lines[2], "Listed: 2026-01-01T00:00:00Z")


