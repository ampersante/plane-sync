class _ApiV2GetPatch:
    """Patches plane_snapshot.api_v2_get and records the params of each call."""

    def __init__(self, test, responder):
        self.test = test
        self.calls = []
        self._responder = responder
        self._old = plane_snapshot.api_v2_get
        plane_snapshot.api_v2_get = self._call

    def _call(self, path, params=None):
        self.calls.append(dict(params or {}))
        return self._responder(len(self.calls) - 1, path, params)

    def restore(self):
        plane_snapshot.api_v2_get = self._old


class FetchChangedEarlyStopTests(unittest.TestCase):
    """CHK-06: the listing stops at the first row older than the watermark;
    the next page is NOT requested."""

    def setUp(self):
        self.watermark = parse_iso_ts("2026-01-01T00:00:00Z")

    def test_stops_on_first_row_older_than_watermark(self):
        new_row = {"id": "u1", "updated_at": "2026-01-02T00:00:00Z"}
        old_row = {"id": "u2", "updated_at": "2025-12-31T00:00:00Z"}
        patch = _ApiV2GetPatch(self, lambda page, path, params: {
            "data": [new_row, old_row], "has_more": True, "next_cursor": "c2"})
        try:
            changed = fetch_changed_items_v2(self.watermark, include_descriptions=False)
        finally:
            patch.restore()
        self.assertEqual([r["id"] for r in changed], ["u1"])
        self.assertEqual(len(patch.calls), 1)  # next page never requested
        self.assertEqual(patch.calls[0].get("order_by"), "-updated_at")
        self.assertNotIn("cursor", patch.calls[0])

    def test_page_boundary_rows_at_or_after_watermark_are_kept(self):
        page1 = [{"id": "u1", "updated_at": "2026-01-03T00:00:00Z"},
                 {"id": "u2", "updated_at": "2026-01-02T00:00:00Z"}]
        page2 = [{"id": "u3", "updated_at": "2026-01-01T00:00:00Z"},
                 {"id": "u4", "updated_at": "2025-12-31T00:00:00Z"}]

        def responder(page, path, params):
            if page == 0:
                self.assertNotIn("cursor", params)
                return {"data": page1, "has_more": True, "next_cursor": "c2"}
            self.assertEqual(params.get("cursor"), "c2")
            return {"data": page2, "has_more": True, "next_cursor": "c3"}

        patch = _ApiV2GetPatch(self, responder)
        try:
            changed = fetch_changed_items_v2(self.watermark, include_descriptions=False)
        finally:
            patch.restore()
        # u3 sits exactly on the watermark → changed; the row after it is older
        # → stop; page 3 (c3) never requested.
        self.assertEqual([r["id"] for r in changed], ["u1", "u2", "u3"])
        self.assertEqual(len(patch.calls), 2)

    def test_descriptions_mode_requests_explicit_fields_list(self):
        new_row = {"id": "u1", "updated_at": "2026-01-02T00:00:00Z",
                   "description_html": "<p>x</p>"}
        old_row = {"id": "u2", "updated_at": "2025-12-31T00:00:00Z"}

        def responder(page, path, params):
            self.assertEqual(params.get("fields"),
                             plane_snapshot.V2_FIELDS_WITH_DESCRIPTIONS)
            self.assertIn("description_html", params["fields"])
            return {"data": [new_row, old_row], "has_more": False}

        patch = _ApiV2GetPatch(self, responder)
        try:
            changed = fetch_changed_items_v2(self.watermark, include_descriptions=True)
        finally:
            patch.restore()
        self.assertEqual([r["id"] for r in changed], ["u1"])


class WatermarkFromListedTests(unittest.TestCase):
    """CHK-05 red gate: the watermark comes from the `Listed:` line, not from
    `Generated:`. A file with Listed < Generated and an item updated inside
    that window must be refetched; a Generated:-based implementation skips it
    and this test fails."""

    def test_item_in_listed_generated_window_is_refetched(self):
        prev = parse_prev_snapshot(_PREV_SNAPSHOT)
        self.assertEqual(prev["listed"], "2026-01-01T11:00:00Z")
        watermark = parse_iso_ts(prev["listed"])
        # Listed (11:00) < updated_at < Generated (12:00)
        row_ts = "2026-01-01T11:30:00Z"
        self.assertLess(parse_iso_ts(row_ts), parse_iso_ts("2026-01-01T12:00:00Z"))
        row = {"id": "u1", "updated_at": row_ts}

        patch = _ApiV2GetPatch(self, lambda page, path, params: {
            "data": [row], "has_more": False})
        try:
            changed = fetch_changed_items_v2(watermark, include_descriptions=False)
        finally:
            patch.restore()
        self.assertEqual([r["id"] for r in changed], ["u1"])


